export function widgetStrings(language: string | null | undefined): WidgetStrings {
  return STRINGS[language ?? ""] ?? en;
}

export function defaultGreeting(language: string | null | undefined, businessName: string): string {
  return widgetStrings(language).greeting.replace("{name}", businessName);
}

export const RTL_LANGUAGES = ["Arabic"];

const CODES: Record<string, string> = {
  en: "English", fr: "French", rw: "Kinyarwanda", sw: "Swahili", es: "Spanish", pt: "Portuguese", ar: "Arabic",
  de: "German", it: "Italian", nl: "Dutch", hi: "Hindi", zh: "Chinese (Simplified)", ja: "Japanese", tr: "Turkish", id: "Indonesian",
};

/** A supported language name from an English name ("French", "chinese") or a browser tag ("fr-FR"); null if unsupported. */
export function supportedLanguage(value: string | null | undefined): string | null {
  const v = value?.trim().toLowerCase();
  if (!v || v.length > 40) return null;
  const byCode = CODES[v.split(/[-_]/)[0]];
  if (/^[a-z]{2,3}([-_][a-z0-9]+)*$/.test(v) && byCode) return byCode;
  return Object.keys(STRINGS).find((name) => name.toLowerCase() === v || name.toLowerCase().startsWith(`${v} `) || v.startsWith(name.toLowerCase())) ?? null;
}

/** Language of the fallback texts: what the visitor writes in (session), else their browser, else the business's. */
export function resolveLanguage(input: { sessionLanguage?: string | null; hint?: string | null; contentLanguage: string }): string {
  return supportedLanguage(input.sessionLanguage) ?? supportedLanguage(input.hint) ?? input.contentLanguage;
}
